import numpy as np


## 1. 기본 펜시 인덱싱
arr = np.array([10, 20, 30, 40, 50])

# (1) 리스트를 직접 넣기
result_a = arr[[0, 2, 4]] 

# (2) 인덱스 변수를 따로 선언해서 넣기
idx = [0, 2, 4]
result_b = arr[idx]
# 결과: [10, 30, 50]



## 2. 다차원 팬시 인덱싱
arr2d = np.array([
    [10, 20, 30],
    [40, 50, 60],
    [70, 80, 90]
])

# (1) 특정 행 선택: 0번과 2번 행만 추출
# (행 0, 2 선택)
rows = arr2d[[0, 2]]
# 결과: [[10, 20, 30],
#        [70, 80, 90]]
print(rows)

# (2) 특정 좌표 선택: (0,0)과 (1,2) 추출
# [행 인덱스 리스트], [열 인덱스 리스트]
# 특정 행·열 좌표를 짝지어 선택 (0행 1열, 1행 2열, 2행 0열)
row_idx = [0, 1, 2]
col_idx = [1, 2, 0]
points = arr2d[row_idx, col_idx]
# 결과: [20, 60, 70]

print(points)

# (3) 여러 행에서 원하는 열만 추출 (행 0,2 에서 열 0,2 만)
submatrix = arr2d[[0, 2]][:, [0, 2]]
# 결과: [[10, 30],
#        [70, 90]]

print(submatrix)